def pick_telepathy(rounds: int, rng: random.Random) -> list[dict[str, str]]:
    picked = rng.sample(TELEPATHY_PAIRS, min(rounds, len(TELEPATHY_PAIRS)))
    return [{"a": a, "b": b} for a, b in picked]


def pick_traits(rng: random.Random) -> list[str]:
    return list(rng.choice(TRAIT_SETS))


def pick_liar_words(rounds: int, rng: random.Random) -> list[dict[str, str]]:
    picked = rng.sample(LIAR_WORD_PAIRS, min(rounds, len(LIAR_WORD_PAIRS)))
    return [{"major": major, "minor": minor} for major, minor in picked]
